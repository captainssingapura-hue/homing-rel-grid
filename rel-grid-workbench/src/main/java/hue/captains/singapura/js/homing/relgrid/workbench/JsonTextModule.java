package hue.captains.singapura.js.homing.relgrid.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The JSON text party's type, as the page has it: {@code JSON_TEXT}, generated from {@link
 * JsonText#TYPE} - so every message is checked against what Java declared.
 */
public record JsonTextModule() implements EsModule<JsonTextModule>, SelfContent {

    public static final JsonTextModule INSTANCE = new JsonTextModule();

    public record JSON_TEXT() implements Exportable._Constant<JsonTextModule> {}

    @Override public ImportsFor<JsonTextModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<JsonTextModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new JSON_TEXT())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by JsonTextModule from JsonText.TYPE - do not hand-edit.", JsonText.TYPE.js());
    }
}
