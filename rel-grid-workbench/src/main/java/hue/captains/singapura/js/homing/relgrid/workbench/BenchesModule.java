package hue.captains.singapura.js.homing.relgrid.workbench;

import hue.captains.singapura.js.homing.core.DomModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The benches as the page has them: {@code WORKBENCH_WORKSPACES} - each bench's manifest, its
 * kinds and its root parties - generated from {@link Benches#SITE}. It imports every widget the
 * benches make, so it is a DOM module.
 */
public record BenchesModule() implements DomModule<BenchesModule>, SelfContent {

    public static final BenchesModule INSTANCE = new BenchesModule();

    public record WORKBENCH_WORKSPACES() implements Exportable._Constant<BenchesModule> {}

    @Override public ImportsFor<BenchesModule> imports() { return Benches.SITE.manifestsImports(); }

    @Override
    public ExportsOf<BenchesModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_WORKSPACES())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by BenchesModule from Benches.SITE - do not hand-edit: each bench's kinds, and its root parties.",
                       Benches.SITE.manifestsJs("WORKBENCH_WORKSPACES"));
    }
}
