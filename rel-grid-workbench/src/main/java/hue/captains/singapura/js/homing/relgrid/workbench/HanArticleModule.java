package hue.captains.singapura.js.homing.relgrid.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The Han article party's type, as the page has it: {@code HAN_ARTICLE}, generated from {@link
 * HanArticle#TYPE} - so every message is checked against what Java declared.
 */
public record HanArticleModule() implements EsModule<HanArticleModule>, SelfContent {

    public static final HanArticleModule INSTANCE = new HanArticleModule();

    public record HAN_ARTICLE() implements Exportable._Constant<HanArticleModule> {}

    @Override public ImportsFor<HanArticleModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<HanArticleModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new HAN_ARTICLE())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by HanArticleModule from HanArticle.TYPE - do not hand-edit.", HanArticle.TYPE.js());
    }
}
