package hue.captains.singapura.js.homing.relgrid.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * The games catalogue as the page has it: {@code GAMES_CATALOGUE}, the pipe-separated text a
 * {@code GamesStore} reads, generated from {@link GamesDataset}. Data: no DOM.
 */
public record GamesDatasetModule() implements EsModule<GamesDatasetModule>, SelfContent {

    public static final GamesDatasetModule INSTANCE = new GamesDatasetModule();

    public record GAMES_CATALOGUE() implements Exportable._Constant<GamesDatasetModule> {}

    @Override public ImportsFor<GamesDatasetModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<GamesDatasetModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new GAMES_CATALOGUE())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by GamesDatasetModule from games-1990-2020.psv - do not hand-edit.",
                       "const GAMES_CATALOGUE = " + JsText.literal(GamesDataset.psv()) + ";");
    }
}
