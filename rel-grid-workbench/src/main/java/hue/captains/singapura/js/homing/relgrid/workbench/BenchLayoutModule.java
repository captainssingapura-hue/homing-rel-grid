package hue.captains.singapura.js.homing.relgrid.workbench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;

import java.util.List;

/**
 * Where the benches are filed and how each is arranged the first time, as the page has them:
 * {@code WORKBENCH_GROUPS} and {@code WORKBENCH_ARRANGEMENTS}, generated from {@link
 * Benches#SITE}. Data: no DOM.
 */
public record BenchLayoutModule() implements EsModule<BenchLayoutModule>, SelfContent {

    public static final BenchLayoutModule INSTANCE = new BenchLayoutModule();

    public record WORKBENCH_GROUPS() implements Exportable._Constant<BenchLayoutModule> {}
    public record WORKBENCH_ARRANGEMENTS() implements Exportable._Constant<BenchLayoutModule> {}

    @Override public ImportsFor<BenchLayoutModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<BenchLayoutModule> exports() {
        return new ExportsOf<>(INSTANCE, List.of(new WORKBENCH_GROUPS(), new WORKBENCH_ARRANGEMENTS()));
    }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by BenchLayoutModule from Benches.SITE - do not hand-edit.",
                       Benches.SITE.groupsJs("WORKBENCH_GROUPS"),
                       Benches.SITE.arrangementsJs("WORKBENCH_ARRANGEMENTS"));
    }
}
